/// Linux deterministic machine id (`/etc/machine-id`), else empty — see Chromium
/// `services/preferences/tracked/device_id*.cc`.
pub fn linux_device_id() -> String {
    fs::read_to_string("/etc/machine-id")
        .map(|s| s.trim().to_string())
        .unwrap_or_default()
}

/// Legacy Chromium transform still applied before HMAC on some builds.
pub fn metrics_device_id(raw: &str) -> String {
    if raw.is_empty() {
        return String::new();
    }
    let mut mac = HmacSha256::new_from_slice(raw.as_bytes()).expect("HMAC accepts any key length");
    mac.update(b"PrefMetricsService");
    hex_upper(&mac.finalize().into_bytes())
}

fn remove_empty(val: &mut Value) {
    // Mirrors Chromium RemoveEmptyValueDictEntries/ListEntries: empty dict
    // and list values are dropped recursively (including list items); nulls
    // and scalars are kept.
    match val {
        Value::Object(map) => {
            map.retain(|_, v| {
                remove_empty(v);
                !matches!(v, Value::Object(m) if m.is_empty())
                    && !matches!(v, Value::Array(a) if a.is_empty())
            });
        }
        Value::Array(arr) => {
            arr.retain_mut(|v| {
                remove_empty(v);
                !matches!(v, Value::Object(m) if m.is_empty())
                    && !matches!(v, Value::Array(a) if a.is_empty())
            });
        }
        _ => {}
    }
}

/// Chromium device id used by the pref hash (pref_hash_store_impl.cc
/// GenerateDeviceId: the raw GetDeterministicMachineSpecificId string, or
/// empty when the platform has none). Linux has no implementation
/// (device_id_stub.cc returns NOT_IMPLEMENTED), so the id is empty there.
/// macOS uses the IOPlatformUUID of IOPlatformExpertDevice as printed
/// (device_id_mac.cc); a failed read is empty, like Chromium. Windows keeps
/// the legacy metrics transform for now.
pub fn chromium_device_id() -> String {
    #[cfg(target_os = "linux")]
    {
        String::new()
    }
    #[cfg(target_os = "macos")]
    {
        mac_platform_uuid().unwrap_or_default()
    }
    #[cfg(not(any(target_os = "linux", target_os = "macos")))]
    {
        metrics_device_id(&linux_device_id())
    }
}

/// The machine's IOPlatformUUID, read the way `ioreg` prints it.
#[cfg(target_os = "macos")]
fn mac_platform_uuid() -> Option<String> {
    let out = std::process::Command::new("/usr/sbin/ioreg")
        .args(["-rd1", "-c", "IOPlatformExpertDevice"])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    parse_ioreg_platform_uuid(&String::from_utf8_lossy(&out.stdout))
}

/// Pull `"IOPlatformUUID" = "<uuid>"` out of `ioreg` output, unchanged.
#[cfg(any(target_os = "macos", test))]
fn parse_ioreg_platform_uuid(out: &str) -> Option<String> {
    let line = out.lines().find(|l| l.contains("\"IOPlatformUUID\""))?;
    let value = line.split_once('=')?.1.trim();
    let uuid = value.strip_prefix('"')?.strip_suffix('"')?;
    (!uuid.is_empty()).then(|| uuid.to_string())
}

fn escape_json_string(s: &str, out: &mut String) {
    // base/json/string_escape.cc EscapeJSONString: only the listed escapes;
    // notably '<' is escaped as a unicode escape while '>' is left alone.
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '<' => out.push_str("\\u003C"),
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04X}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
}

fn write_canonical(value: &Value, out: &mut String) {
    // base::WriteJson: compact, dictionary keys in sorted order.
    match value {
        Value::Null => out.push_str("null"),
        Value::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        Value::Number(n) => out.push_str(&n.to_string()),
        Value::String(s) => escape_json_string(s, out),
        Value::Array(arr) => {
            out.push('[');
            for (i, v) in arr.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_canonical(v, out);
            }
            out.push(']');
        }
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            out.push('{');
            for (i, k) in keys.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                escape_json_string(k, out);
                out.push(':');
                write_canonical(&map[*k], out);
            }
            out.push('}');
        }
    }
}

fn value_as_string(value: &Value) -> Result<String> {
    let mut v = value.clone();
    remove_empty(&mut v);
    let mut out = String::new();
    write_canonical(&v, &mut out);
    Ok(out)
}

fn hex_upper(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02X}")).collect()
}

fn hmac_hex(seed: &[u8], device_id: &str, path: &str, value: &Value) -> Result<String> {
    let body = value_as_string(value)?;
    let mut msg = String::with_capacity(device_id.len() + path.len() + body.len());
    msg.push_str(device_id);
    msg.push_str(path);
    msg.push_str(&body);
    let mut mac = HmacSha256::new_from_slice(seed).map_err(|e| Error::Io(e.to_string()))?;
    mac.update(msg.as_bytes());
    Ok(hex_upper(&mac.finalize().into_bytes()))
}

fn calculate_super_mac(seed: &[u8], device_id: &str, macs: &Value) -> Result<String> {
    // PrefHashStoreImpl validates the super MAC as an HMAC over the whole
    // macs dict with an empty path; a store holding no macs hashes the empty
    // string instead (ValueAsString of a null contents value).
    let body = match macs {
        Value::Object(m) if m.is_empty() => String::new(),
        _ => value_as_string(macs)?,
    };
    let mut msg = String::with_capacity(device_id.len() + body.len());
    msg.push_str(device_id);
    msg.push_str(&body);
    let mut mac = HmacSha256::new_from_slice(seed).map_err(|e| Error::Io(e.to_string()))?;
    mac.update(msg.as_bytes());
    Ok(hex_upper(&mac.finalize().into_bytes()))
}

/// The target's OSCrypt lock plus the label its folder seals
/// encrypted-hash anchors under, as decided by the caller from the
/// folder's own labels. Every anchor the merge writes (the
/// per-extension settings anchors and the super anchor) is sealed
/// under that label, mirroring the anchors the folder already
/// carries: a folder born while its keychain was unavailable seals
/// v10 and carries v10 anchors of Chrome's own, and its anchors are
/// expected under that label there.
pub type AnchorLock<'a> = (&'a Lock, LinuxPrefix);

/// One OSCrypt encrypted-hash anchor, the value Chrome seals into
/// `protection.super_encrypted_hash` and
/// `protection.macs.extensions.settings_encrypted_hash.<id>`:
/// base64(label || AES-128-CBC-PKCS7(the label's key, IV = sixteen
/// 0x20 bytes, raw SHA256(seed || path || canonical JSON of the
/// value))). The label is the one the target folder seals with: v11
/// takes the pepper key from the target lock's v11 slot (`Lock::mac`
/// derives it from the browser's Safe Storage password with salt
/// "pepper", 1003 rounds), v10 the saltysalt key in the main slot;
/// the device id is not an input. The v11 recipe is pinned
/// byte-for-byte by the Mac probes (round 1: 9/9 of Chrome's own
/// anchors; round 2: the inherited anchors and Chrome's own
/// Bitwarden anchor verify, Q2/Q4); the v10 form mirrors the anchors
/// Chrome itself wrote into the v10-sealing default-directory
/// profile (fix 3 round 3).
fn encrypted_hash_anchor(seed: &[u8], path: &str, value: &Value, anchor: AnchorLock) -> Result<String> {
    let (lock, label) = anchor;
    let body = value_as_string(value)?;
    let mut h = Sha256::new();
    h.update(seed);
    h.update(path.as_bytes());
    h.update(body.as_bytes());
    let digest: [u8; 32] = h.finalize().into();
    let sealed = lock.seal_anchor_raw(&digest, label).ok_or_else(|| {
        Error::Refused(format!(
            "cannot seal an extension registration anchor: the target browser key has no {} key",
            match label {
                LinuxPrefix::V10 => "v10 (saltysalt)",
                LinuxPrefix::V11 => "v11 (pepper)",
            }
        ))
    })?;
    Ok(base64::engine::general_purpose::STANDARD.encode(sealed))
}

/// Write the `settings_encrypted_hash` anchor for every registration this
/// merge installs, computed over the final merged entry exactly as it
/// sits in the file. Anchors already present for other ids are left
/// untouched. Fails loudly when the target key cannot seal an anchor: a
/// registration written without its anchor is stripped by Chrome on
/// macOS at first startup, so the merge must not go through without one.
fn stamp_settings_anchors(
    root: &mut Value,
    settings: &Map<String, Value>,
    regs: &Map<String, Value>,
    seed: &[u8],
    anchor: AnchorLock,
) -> Result<()> {
    // Seal every anchor before mutating the tree, so a key failure
    // leaves the file exactly as it was.
    let mut anchors = Map::new();
    for id in regs.keys() {
        let entry = settings.get(id).ok_or_else(|| {
            Error::Corrupt(format!("merged settings are missing extension {id}"))
        })?;
        let path = format!("extensions.settings.{id}");
        anchors.insert(id.clone(), json!(encrypted_hash_anchor(seed, &path, entry, anchor)?));
    }
    let hashes = root
        .as_object_mut()
        .and_then(|o| o.entry("protection").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|p| p.entry("macs").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|m| m.entry("extensions").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|e| e.entry("settings_encrypted_hash").or_insert_with(|| json!({})).as_object_mut());
    let Some(hashes) = hashes else {
        return Err(Error::Corrupt(
            "cannot build protection.macs.extensions.settings_encrypted_hash".into(),
        ));
    };
    for (id, anchor) in anchors {
        hashes.insert(id, anchor);
    }
    Ok(())
}

/// The macs tree pruned to its `*_encrypted_hash` leaves: an entry
/// survives when its key names an encrypted hash (its whole value goes
/// along, e.g. the flat id-to-anchor map under `settings_encrypted_hash`)
/// or when a descendant survives; every other entry is dropped. This
/// filtered tree is what the super anchor seals (probe-verified against
/// Chrome's own `super_encrypted_hash`, fix 3 round 2 Q1: MATCH).
fn filter_encrypted_only(value: &Value) -> Value {
    // Mirrors the probe's filter_encrypted_only exactly: a key ending in
    // "_encrypted_hash" keeps its whole value; any other dict value is
    // replaced by its own filtered form and kept only when that is
    // non-empty; anything else is dropped, and a non-dict input filters
    // to an empty dict.
    let mut out = Map::new();
    if let Value::Object(map) = value {
        for (k, v) in map {
            if k.ends_with("_encrypted_hash") {
                out.insert(k.clone(), v.clone());
            } else if v.is_object() {
                let sub = filter_encrypted_only(v);
                if !matches!(&sub, Value::Object(m) if m.is_empty()) {
                    out.insert(k.clone(), sub);
                }
            }
        }
    }
    Value::Object(out)
}

/// Recompute `protection.super_encrypted_hash` over the final macs tree:
/// the anchor recipe with an empty path over the filtered tree. Adding a
/// per-extension anchor changes the filtered tree, so an inherited super
/// anchor goes stale by construction the moment fix A stamps a new one;
/// leaving it would hand Chrome an internally inconsistent protection
/// block.
fn stamp_super_encrypted_hash(root: &mut Value, seed: &[u8], anchor: AnchorLock) -> Result<()> {
    let macs = root
        .get("protection")
        .and_then(|p| p.get("macs"))
        .cloned()
        .unwrap_or(json!({}));
    let anchor = encrypted_hash_anchor(seed, "", &filter_encrypted_only(&macs), anchor)?;
    let prot = root
        .as_object_mut()
        .and_then(|o| o.entry("protection").or_insert_with(|| json!({})).as_object_mut());
    let Some(prot) = prot else {
        return Err(Error::Corrupt("cannot build protection in preferences".into()));
    };
    prot.insert("super_encrypted_hash".into(), json!(anchor));
    Ok(())
}

pub fn uses_secure_extension_prefs(browser: &str) -> bool {
    // The whole Brave family keeps registrations in plain Preferences
    // only. The registry's channel rows (brave-beta, brave-nightly)
    // record the stable browser they belong to, so the family match
    // goes through the registry rather than the exact id string: a
    // channel build named here must not take the Chrome secure-prefs
    // merge just because its id is not literally "brave".
    match crate::browsers::by_id(browser) {
        Some(def) => !(def.id == "brave" || def.channel_of == Some("brave")),
        None => !matches!(browser, "brave"),
    }
}

pub fn seed_for_browser(browser: &str) -> &'static [u8] {
    // Only the Google Chrome family seals pref hashes under the
    // Google seed. Rig fixtures written by the real browsers prove
    // the empty (Chromium OSS) seed for every other family: Brave
    // (brave-beta 1.101, brave-nightly 1.102), Edge (edge-beta,
    // edge-dev), Vivaldi, Opera and Opera GX all store the empty-seed
    // empty-store super_mac, while chrome, chrome-beta and
    // chrome-dev store the Google-seed constant. Chromium itself
    // has no rig fixture; its empty seed is the documented OSS
    // behaviour and is unchanged. Chrome Canary has no fixture
    // either and is assumed Google as a Chrome channel. Family is
    // resolved through the registry (channel_of), the same way
    // uses_secure_extension_prefs resolves the Brave family, so a
    // channel build inherits its stable browser's seed.
    match crate::browsers::by_id(browser) {
        Some(def) => {
            if def.channel_of.unwrap_or(def.id) == "chrome" {
                &GOOGLE_CHROME_SEED
            } else {
                &[]
            }
        }
        None => {
            if matches!(browser, "brave" | "chromium") {
                &[]
            } else {
                &GOOGLE_CHROME_SEED
            }
        }
    }
}

fn read_json(path: &Path) -> Result<Value> {
    if !path.is_file() {
        return Ok(json!({}));
    }
    let bytes = fs::read(path).map_err(|e| io(e, "cannot read", path))?;
    serde_json::from_slice(&bytes).map_err(|_| Error::Corrupt(format!("invalid JSON in {}", path.display())))
}

fn write_json(path: &Path, value: &Value) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|e| io(e, "cannot create", parent))?;
    }
    let bytes = serde_json::to_vec(value).map_err(|e| Error::Io(e.to_string()))?;
    fs::write(path, &bytes).map_err(|e| io(e, "cannot write", path))
}

fn macs_for_extensions(root: &mut Value, settings: &Map<String, Value>, seed: &[u8], device_id: &str, stamp_super: bool) -> Result<()> {
    let macs = root
        .as_object_mut()
        .and_then(|o| o.entry("protection").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|p| p.entry("macs").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|m| m.entry("extensions").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|e| e.entry("settings").or_insert_with(|| json!({})).as_object_mut());
    let Some(macs) = macs else {
        return Err(Error::Corrupt("cannot build protection.macs in preferences".into()));
    };
    macs.clear();
    for (id, entry) in settings {
        let path = format!("extensions.settings.{id}");
        macs.insert(id.clone(), json!(hmac_hex(seed, device_id, &path, entry)?));
    }
    if stamp_super {
        stamp_super_mac(root, seed, device_id)?;
    }
    Ok(())
}

/// Stamp `protection.super_mac` over the macs tree exactly as it stands
/// in `root` right now. Callers that go on mutating the macs tree (the
/// gated macOS anchor path inserts `settings_encrypted_hash` leaves
/// after the per-entry HMACs) must stamp this only once the tree is
/// final: PrefHashStoreImpl validates the super MAC over the whole
/// macs dict, so a super stamped earlier is stale by construction.
fn stamp_super_mac(root: &mut Value, seed: &[u8], device_id: &str) -> Result<()> {
    let macs_val = root
        .get("protection")
        .and_then(|p| p.get("macs"))
        .cloned()
        .unwrap_or(json!({}));
    let digest = calculate_super_mac(seed, device_id, &macs_val)?;
    if let Some(prot) = root.as_object_mut().and_then(|o| o.get_mut("protection")).and_then(Value::as_object_mut) {
        prot.insert("super_mac".into(), json!(digest));
    }
    Ok(())
}

fn parse_version(raw: &str) -> Option<Vec<u64>> {
    let mut out = Vec::new();
    for part in raw.split('.') {
        if part.is_empty() || !part.bytes().all(|b| b.is_ascii_digit()) {
            return None;
        }
        out.push(part.parse().ok()?);
    }
    (!out.is_empty()).then_some(out)
}

/// The version a registration entry carries, as a numeric dotted
/// vector: `manifest.version` in the shape Chromium writes, with a
/// top-level `version` as a fallback. The fallback applies whenever
/// the manifest version is absent, not a string, or unparseable as
/// a numeric dotted version: an entry carrying manifest version
/// "abc" and top-level version "9.0" is versioned 9.0, not
/// unversioned, so a lower source can never replace it on the
/// strength of the broken manifest field alone. An entry with no
/// parseable version in either field is unversioned.
fn entry_version(entry: &Value) -> Option<Vec<u64>> {
    if let Some(v) = entry
        .get("manifest")
        .and_then(|m| m.get("version"))
        .and_then(Value::as_str)
        .and_then(parse_version)
    {
        return Some(v);
    }
    entry.get("version").and_then(Value::as_str).and_then(parse_version)
}

fn version_cmp(a: &[u64], b: &[u64]) -> std::cmp::Ordering {
    for i in 0..a.len().max(b.len()) {
        let x = a.get(i).copied().unwrap_or(0);
        let y = b.get(i).copied().unwrap_or(0);
        match x.cmp(&y) {
            std::cmp::Ordering::Equal => {}
            other => return other,
        }
    }
    std::cmp::Ordering::Equal
}

/// The folder an unpacked (developer-mode) registration points at,
/// when the entry carries one: an absolute path outside the profile.
/// Packed and Web Store entries carry a profile-relative path, so an
/// absolute one is the unpacked shape. Windows-shaped absolute paths
/// count too: a sealed box can carry another machine's entry verbatim,
/// and on this machine such a path simply does not exist.
fn unpacked_path(entry: &Value) -> Option<&str> {
    let path = entry.get("path").and_then(Value::as_str)?;
    let windows_absolute = path.len() >= 3
        && path.as_bytes()[1] == b':'
        && matches!(path.as_bytes()[2], b'\\' | b'/');
    (Path::new(path).is_absolute() || windows_absolute || path.starts_with("\\\\")).then_some(path)
}

/// Merge one source registration into a target settings map without
/// ever downgrading what the target already holds:
///
/// - No target entry: the source entry lands, as before.
/// - The source entry is unpacked and its folder does not exist on
///   this machine, while the target already holds an entry for the
///   id: the target's entry stays. The incoming one points at a
///   folder this machine does not have (on the sealed path, a foreign
///   machine's folder), so replacing a working local registration
///   with it would break the extension here.
/// - Both entries carry a version: the source entry replaces the
///   target's only when its version is strictly higher. Tie rule:
///   equal versions keep the target's entry - its path, state and
///   permissions are this machine's own, and an equal-version foreign
///   entry has nothing to add.
/// - Only the target's entry carries a version: it stays (the source
///   entry cannot prove it is newer). Only the source's, or neither:
///   the source entry lands, as before.
/// Returns true when the source entry landed (it was added, or it
/// replaced the target's entry), false when the target's entry was
/// kept. Callers that own side effects keyed by registration id
/// (the Brave Secure Preferences strip) must act only on landed ids.
fn merge_entry(settings: &mut Map<String, Value>, id: &str, entry: &Value) -> bool {
    let Some(existing) = settings.get(id) else {
        settings.insert(id.to_string(), entry.clone());
        return true;
    };
    if let Some(path) = unpacked_path(entry) {
        if !Path::new(path).exists() {
            return false;
        }
    }
    match (entry_version(existing), entry_version(entry)) {
        (Some(have), Some(incoming)) => {
            if version_cmp(&incoming, &have) == std::cmp::Ordering::Greater {
                settings.insert(id.to_string(), entry.clone());
                true
            } else {
                false
            }
        }
        (Some(_), None) => false,
        _ => {
            settings.insert(id.to_string(), entry.clone());
            true
        }
    }
}

fn merge_into_file(root: &mut Value, regs: &Map<String, Value>) -> Result<(Map<String, Value>, Vec<String>)> {
    let ext = root
        .as_object_mut()
        .and_then(|o| o.entry("extensions").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|e| e.entry("settings").or_insert_with(|| json!({})).as_object_mut());
    let Some(ext) = ext else {
        return Err(Error::Corrupt("cannot merge into preferences file".into()));
    };
    let mut landed = Vec::new();
    for (id, entry) in regs {
        if merge_entry(&mut *ext, id, entry) {
            landed.push(id.clone());
        }
    }
    Ok((ext.clone(), landed))
}

/// Merge extension registrations for Chrome-family targets.
///
/// Chrome 157 on Linux keeps `extensions.settings` and their MACs in plain
/// `Preferences` (verified live: a registration written only to
/// `Secure Preferences` is never read, while one in `Preferences` loads and
/// Chrome re-signs it). Registrations therefore go into `Preferences` with
/// freshly computed split MACs, and are mirrored into `Secure Preferences`
/// with MACs plus the super MAC for builds that read the protected store.
/// In `Preferences` the OSCrypt encrypted-hash anchors are dropped: that
/// copy is not the authoritative store on macOS and Linux Chrome re-signs
/// what it reads there. In `Secure Preferences`, when the caller passes
/// the target's macOS anchor lock (`anchor_lock`: the lock plus the
/// label the folder seals with), each installed extension also gets
/// its `settings_encrypted_hash` anchor, sealed under that label: on
/// macOS Chrome does NOT regenerate a missing anchor for a third-party
/// entry, it strips the entry and deletes its files at first startup
/// (fix 3 round 2; the strip hits v10-sealing folders the same way,
/// round 3). Without a lock (Linux, Windows) no anchor is written,
/// exactly as before.
pub fn merge_registrations_secure(
    slot: &Path,
    browser: &str,
    regs: &Map<String, Value>,
    anchor_lock: Option<AnchorLock>,
) -> Result<usize> {
    if regs.is_empty() {
        return Ok(0);
    }
    let seed = seed_for_browser(browser);
    let device_id = chromium_device_id();

    let prefs_path = slot.join("Preferences");
    let mut prefs = read_json(&prefs_path)?;
    let (settings, _) = merge_into_file(&mut prefs, regs)?;
    macs_for_extensions(&mut prefs, &settings, seed, &device_id, false)?;
    if let Some(prot) = prefs
        .as_object_mut()
        .and_then(|o| o.get_mut("protection"))
        .and_then(Value::as_object_mut)
    {
        prot.remove("super_encrypted_hash");
        if let Some(ext) = prot
            .get_mut("macs")
            .and_then(|m| m.get_mut("extensions"))
            .and_then(Value::as_object_mut)
        {
            ext.remove("settings_encrypted_hash");
        }
    }
    let secure_path = slot.join("Secure Preferences");
    let mut secure = read_json(&secure_path)?;
    let (secure_settings, _) = merge_into_file(&mut secure, regs)?;
    if let Some(anchor) = anchor_lock {
        // Gated macOS path: per-entry HMACs first without the super,
        // then the encrypted-hash anchors (which mutate the macs tree),
        // then BOTH supers last over the finished tree. Stamping
        // super_mac inside macs_for_extensions here would leave it
        // covering the pre-anchor tree: the same stale-super defect
        // the super_encrypted_hash recompute fixed, one layer over.
        macs_for_extensions(&mut secure, &secure_settings, seed, &device_id, false)?;
        stamp_settings_anchors(&mut secure, &secure_settings, regs, seed, anchor)?;
        stamp_super_mac(&mut secure, seed, &device_id)?;
        stamp_super_encrypted_hash(&mut secure, seed, anchor)?;
    } else {
        macs_for_extensions(&mut secure, &secure_settings, seed, &device_id, true)?;
    }
    // Both files are written only after every fallible step above has
    // succeeded, so a seal failure (keyless lock) leaves Preferences
    // and Secure Preferences exactly as they were for direct callers
    // without a journal around this merge.
    write_json(&prefs_path, &prefs)?;
    write_json(&secure_path, &secure)?;
    Ok(regs.len())
}

/// Brave keeps registrations in plain `Preferences` only.
pub fn merge_registrations_brave(slot: &Path, regs: &Map<String, Value>) -> Result<usize> {
    merge_registrations_brave_inner(slot, regs, None)
}

fn merge_registrations_brave_inner(
    slot: &Path,
    regs: &Map<String, Value>,
    anchor_lock: Option<AnchorLock>,
) -> Result<usize> {
    if regs.is_empty() {
        return Ok(0);
    }
    let prefs_path = slot.join("Preferences");
    let mut prefs = read_json(&prefs_path)?;
    let settings = prefs
        .as_object_mut()
        .and_then(|o| o.entry("extensions").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|e| e.entry("settings").or_insert_with(|| json!({})).as_object_mut());
    let Some(settings) = settings else {
        return Err(Error::Corrupt(format!("cannot merge into {}", prefs_path.display())));
    };
    let mut n = 0;
    let mut landed = Vec::new();
    for (id, entry) in regs {
        if merge_entry(&mut *settings, id, entry) {
            landed.push(id.clone());
        }
        n += 1;
    }
    // Compute the Secure Preferences strip (including both super
    // stamps / the seal) before any file is written, mirroring the
    // secure path: both files are written only after every fallible
    // step has succeeded, so a seal failure leaves Preferences and
    // Secure Preferences exactly as they were.
    let secure_update = prepare_secure_prefs_for_brave(slot, &landed, anchor_lock)?;
    write_json(&prefs_path, &prefs)?;
    if let Some((secure_path, secure)) = secure_update {
        write_json(&secure_path, &secure)?;
    }
    Ok(n)
}

/// Brave does not read `Secure Preferences` for extension
/// registrations, but the file is the target's own protected store:
/// it carries other extensions' registrations and unrelated protected
/// keys, and deleting it outright (the old behaviour) destroyed all
/// of that in the live profile the moment a move landed. This merge
/// owns only the registrations it actually landed in plain
/// `Preferences`, so only those ids are stripped from the secure
/// file - from `extensions.settings` and from the pref-hash macs
/// keyed by the same ids - and everything else is left exactly as it
/// was. An id the merge did not land (its target entry was kept:
/// version-blocked, or blocked by the unpacked foreign-path guard)
/// keeps its secure registration and MAC untouched, because the
/// target's own entry is still the live one there.
///
/// Removing entries and MACs invalidates the file's super MACs, so
/// a strip restamps them with the same helpers the secure merge
/// uses (`stamp_super_mac`, and `stamp_super_encrypted_hash` when
/// the file carries one and the caller passed the target's anchor
/// lock). When the file carries a `super_encrypted_hash` but no
/// anchor lock is available to restamp it, the file is left
/// entirely untouched instead: a rewrite with a stale super anchor
/// would be internally inconsistent, and the unstripped
/// registration is a duplicate of the one now in `Preferences`,
/// which is the store Brave actually reads. The file is rewritten
/// only when something was actually stripped, so an untouched file
/// stays byte-identical, and a file that cannot be parsed is left
/// alone rather than deleted or failed over. Undo never depends on
/// this: the journal restores the file byte-for-byte either way.
///
/// This only prepares the stripped file in memory, stamps and seal
/// included; the caller writes it (and `Preferences`) only after
/// this has succeeded, so a fallible stamp or seal cannot leave a
/// partially applied merge behind.
fn prepare_secure_prefs_for_brave(
    slot: &Path,
    landed: &[String],
    anchor_lock: Option<AnchorLock>,
) -> Result<Option<(std::path::PathBuf, Value)>> {
    if landed.is_empty() {
        return Ok(None);
    }
    let secure_path = slot.join("Secure Preferences");
    if !secure_path.is_file() {
        return Ok(None);
    }
    let Ok(mut secure) = read_json(&secure_path) else {
        return Ok(None);
    };
    let mut would_change = false;
    if let Some(settings) = secure
        .get("extensions")
        .and_then(|e| e.get("settings"))
        .and_then(Value::as_object)
    {
        would_change |= landed.iter().any(|id| settings.contains_key(id));
    }
    if let Some(macs) = secure
        .get("protection")
        .and_then(|p| p.get("macs"))
        .and_then(|m| m.get("extensions"))
        .and_then(Value::as_object)
    {
        for key in ["settings", "settings_encrypted_hash"] {
            if let Some(by_id) = macs.get(key).and_then(Value::as_object) {
                would_change |= landed.iter().any(|id| by_id.contains_key(id));
            }
        }
    }
    if !would_change {
        return Ok(None);
    }
    // Presence check, not a string check: any present, non-null
    // value counts as carrying a super_encrypted_hash, so a
    // malformed (e.g. numeric) one still gates the strip below
    // instead of being left stale by it.
    let had_super_encrypted = secure
        .get("protection")
        .and_then(|p| p.get("super_encrypted_hash"))
        .map_or(false, |v| !v.is_null());
    if had_super_encrypted && anchor_lock.is_none() {
        return Ok(None);
    }
    let mut changed = false;
    if let Some(settings) = secure
        .get_mut("extensions")
        .and_then(|e| e.get_mut("settings"))
        .and_then(Value::as_object_mut)
    {
        for id in landed {
            changed |= settings.remove(id).is_some();
        }
    }
    if let Some(macs) = secure
        .get_mut("protection")
        .and_then(|p| p.get_mut("macs"))
        .and_then(|m| m.get_mut("extensions"))
        .and_then(Value::as_object_mut)
    {
        for key in ["settings", "settings_encrypted_hash"] {
            if let Some(by_id) = macs.get_mut(key).and_then(Value::as_object_mut) {
                for id in landed {
                    changed |= by_id.remove(id).is_some();
                }
            }
        }
    }
    if changed {
        let seed = seed_for_browser("brave");
        let device_id = chromium_device_id();
        stamp_super_mac(&mut secure, seed, &device_id)?;
        if had_super_encrypted {
            if let Some(anchor) = anchor_lock {
                stamp_super_encrypted_hash(&mut secure, seed, anchor)?;
            }
        }
        return Ok(Some((secure_path, secure)));
    }
    Ok(None)
}

pub fn merge_registrations(
    slot: &Path,
    browser: &str,
    regs: &Map<String, Value>,
    anchor_lock: Option<AnchorLock>,
) -> Result<usize> {
    if uses_secure_extension_prefs(browser) {
        merge_registrations_secure(slot, browser, regs, anchor_lock)
    } else {
        merge_registrations_brave_inner(slot, regs, anchor_lock)
    }
}

