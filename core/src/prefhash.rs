/// Linux deterministic machine id (`/etc/machine-id`), else empty — see Chromium
/// `services/preferences/tracked/device_id*.cc`.
pub fn linux_device_id() -> String {
    fs::read_to_string("/etc/machine-id")
        .map(|s| s.trim().to_string())
        .unwrap_or_default()
}

/// Legacy Chromium transform still applied before HMAC on some builds.
pub fn metrics_device_id(raw: &str) -> String {
    if raw.is_empty() {
        return String::new();
    }
    let mut mac = HmacSha256::new_from_slice(raw.as_bytes()).expect("HMAC accepts any key length");
    mac.update(b"PrefMetricsService");
    hex_upper(&mac.finalize().into_bytes())
}

fn remove_empty(val: &mut Value) {
    // Mirrors Chromium RemoveEmptyValueDictEntries/ListEntries: empty dict
    // and list values are dropped recursively (including list items); nulls
    // and scalars are kept.
    match val {
        Value::Object(map) => {
            map.retain(|_, v| {
                remove_empty(v);
                !matches!(v, Value::Object(m) if m.is_empty())
                    && !matches!(v, Value::Array(a) if a.is_empty())
            });
        }
        Value::Array(arr) => {
            arr.retain_mut(|v| {
                remove_empty(v);
                !matches!(v, Value::Object(m) if m.is_empty())
                    && !matches!(v, Value::Array(a) if a.is_empty())
            });
        }
        _ => {}
    }
}

/// Chromium device id used by the pref hash (pref_hash_store_impl.cc
/// GenerateDeviceId: the raw GetDeterministicMachineSpecificId string, or
/// empty when the platform has none). Linux has no implementation
/// (device_id_stub.cc returns NOT_IMPLEMENTED), so the id is empty there.
/// macOS uses the IOPlatformUUID of IOPlatformExpertDevice as printed
/// (device_id_mac.cc); a failed read is empty, like Chromium. Windows keeps
/// the legacy metrics transform for now.
pub fn chromium_device_id() -> String {
    #[cfg(target_os = "linux")]
    {
        String::new()
    }
    #[cfg(target_os = "macos")]
    {
        mac_platform_uuid().unwrap_or_default()
    }
    #[cfg(not(any(target_os = "linux", target_os = "macos")))]
    {
        metrics_device_id(&linux_device_id())
    }
}

/// The machine's IOPlatformUUID, read the way `ioreg` prints it.
#[cfg(target_os = "macos")]
fn mac_platform_uuid() -> Option<String> {
    let out = std::process::Command::new("/usr/sbin/ioreg")
        .args(["-rd1", "-c", "IOPlatformExpertDevice"])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    parse_ioreg_platform_uuid(&String::from_utf8_lossy(&out.stdout))
}

/// Pull `"IOPlatformUUID" = "<uuid>"` out of `ioreg` output, unchanged.
#[cfg(any(target_os = "macos", test))]
fn parse_ioreg_platform_uuid(out: &str) -> Option<String> {
    let line = out.lines().find(|l| l.contains("\"IOPlatformUUID\""))?;
    let value = line.split_once('=')?.1.trim();
    let uuid = value.strip_prefix('"')?.strip_suffix('"')?;
    (!uuid.is_empty()).then(|| uuid.to_string())
}

fn escape_json_string(s: &str, out: &mut String) {
    // base/json/string_escape.cc EscapeJSONString: only the listed escapes;
    // notably '<' is escaped as a unicode escape while '>' is left alone.
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '<' => out.push_str("\\u003C"),
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04X}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
}

fn write_canonical(value: &Value, out: &mut String) {
    // base::WriteJson: compact, dictionary keys in sorted order.
    match value {
        Value::Null => out.push_str("null"),
        Value::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        Value::Number(n) => out.push_str(&n.to_string()),
        Value::String(s) => escape_json_string(s, out),
        Value::Array(arr) => {
            out.push('[');
            for (i, v) in arr.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_canonical(v, out);
            }
            out.push(']');
        }
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            out.push('{');
            for (i, k) in keys.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                escape_json_string(k, out);
                out.push(':');
                write_canonical(&map[*k], out);
            }
            out.push('}');
        }
    }
}

fn value_as_string(value: &Value) -> Result<String> {
    let mut v = value.clone();
    remove_empty(&mut v);
    let mut out = String::new();
    write_canonical(&v, &mut out);
    Ok(out)
}

fn hex_upper(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02X}")).collect()
}

fn hmac_hex(seed: &[u8], device_id: &str, path: &str, value: &Value) -> Result<String> {
    let body = value_as_string(value)?;
    let mut msg = String::with_capacity(device_id.len() + path.len() + body.len());
    msg.push_str(device_id);
    msg.push_str(path);
    msg.push_str(&body);
    let mut mac = HmacSha256::new_from_slice(seed).map_err(|e| Error::Io(e.to_string()))?;
    mac.update(msg.as_bytes());
    Ok(hex_upper(&mac.finalize().into_bytes()))
}

fn calculate_super_mac(seed: &[u8], device_id: &str, macs: &Value) -> Result<String> {
    // PrefHashStoreImpl validates the super MAC as an HMAC over the whole
    // macs dict with an empty path; a store holding no macs hashes the empty
    // string instead (ValueAsString of a null contents value).
    let body = match macs {
        Value::Object(m) if m.is_empty() => String::new(),
        _ => value_as_string(macs)?,
    };
    let mut msg = String::with_capacity(device_id.len() + body.len());
    msg.push_str(device_id);
    msg.push_str(&body);
    let mut mac = HmacSha256::new_from_slice(seed).map_err(|e| Error::Io(e.to_string()))?;
    mac.update(msg.as_bytes());
    Ok(hex_upper(&mac.finalize().into_bytes()))
}

/// One OSCrypt encrypted-hash anchor, the value Chrome seals into
/// `protection.super_encrypted_hash` and
/// `protection.macs.extensions.settings_encrypted_hash.<id>`:
/// base64("v11" || AES-128-CBC-PKCS7(pepper key, IV = sixteen 0x20 bytes,
/// raw SHA256(seed || path || canonical JSON of the value))). The pepper
/// key rides in the target lock's v11 slot (`Lock::mac` derives it from
/// the browser's Safe Storage password with salt "pepper", 1003 rounds);
/// the device id is not an input. The recipe is pinned byte-for-byte by
/// the Mac probes (round 1: 9/9 of Chrome's own anchors; round 2: the
/// inherited anchors and Chrome's own Bitwarden anchor verify, Q2/Q4).
fn encrypted_hash_anchor(seed: &[u8], path: &str, value: &Value, lock: &Lock) -> Result<String> {
    let body = value_as_string(value)?;
    let mut h = Sha256::new();
    h.update(seed);
    h.update(path.as_bytes());
    h.update(body.as_bytes());
    let digest: [u8; 32] = h.finalize().into();
    let sealed = lock.seal_v11_raw(&digest).ok_or_else(|| {
        Error::Refused(
            "cannot seal an extension registration anchor: the target browser key has no v11 (pepper) key"
                .into(),
        )
    })?;
    Ok(base64::engine::general_purpose::STANDARD.encode(sealed))
}

/// Write the `settings_encrypted_hash` anchor for every registration this
/// merge installs, computed over the final merged entry exactly as it
/// sits in the file. Anchors already present for other ids are left
/// untouched. Fails loudly when the target key cannot seal an anchor: a
/// registration written without its anchor is stripped by Chrome on
/// macOS at first startup, so the merge must not go through without one.
fn stamp_settings_anchors(
    root: &mut Value,
    settings: &Map<String, Value>,
    regs: &Map<String, Value>,
    seed: &[u8],
    lock: &Lock,
) -> Result<()> {
    // Seal every anchor before mutating the tree, so a key failure
    // leaves the file exactly as it was.
    let mut anchors = Map::new();
    for id in regs.keys() {
        let entry = settings.get(id).ok_or_else(|| {
            Error::Corrupt(format!("merged settings are missing extension {id}"))
        })?;
        let path = format!("extensions.settings.{id}");
        anchors.insert(id.clone(), json!(encrypted_hash_anchor(seed, &path, entry, lock)?));
    }
    let hashes = root
        .as_object_mut()
        .and_then(|o| o.entry("protection").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|p| p.entry("macs").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|m| m.entry("extensions").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|e| e.entry("settings_encrypted_hash").or_insert_with(|| json!({})).as_object_mut());
    let Some(hashes) = hashes else {
        return Err(Error::Corrupt(
            "cannot build protection.macs.extensions.settings_encrypted_hash".into(),
        ));
    };
    for (id, anchor) in anchors {
        hashes.insert(id, anchor);
    }
    Ok(())
}

pub fn uses_secure_extension_prefs(browser: &str) -> bool {
    !matches!(browser, "brave")
}

pub fn seed_for_browser(browser: &str) -> &'static [u8] {
    if matches!(browser, "chromium") {
        return &[];
    }
    &GOOGLE_CHROME_SEED
}

fn read_json(path: &Path) -> Result<Value> {
    if !path.is_file() {
        return Ok(json!({}));
    }
    let bytes = fs::read(path).map_err(|e| io(e, "cannot read", path))?;
    serde_json::from_slice(&bytes).map_err(|_| Error::Corrupt(format!("invalid JSON in {}", path.display())))
}

fn write_json(path: &Path, value: &Value) -> Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|e| io(e, "cannot create", parent))?;
    }
    let bytes = serde_json::to_vec(value).map_err(|e| Error::Io(e.to_string()))?;
    fs::write(path, &bytes).map_err(|e| io(e, "cannot write", path))
}

fn macs_for_extensions(root: &mut Value, settings: &Map<String, Value>, seed: &[u8], device_id: &str, stamp_super: bool) -> Result<()> {
    let macs = root
        .as_object_mut()
        .and_then(|o| o.entry("protection").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|p| p.entry("macs").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|m| m.entry("extensions").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|e| e.entry("settings").or_insert_with(|| json!({})).as_object_mut());
    let Some(macs) = macs else {
        return Err(Error::Corrupt("cannot build protection.macs in preferences".into()));
    };
    macs.clear();
    for (id, entry) in settings {
        let path = format!("extensions.settings.{id}");
        macs.insert(id.clone(), json!(hmac_hex(seed, device_id, &path, entry)?));
    }
    if stamp_super {
        let macs_val = root
            .get("protection")
            .and_then(|p| p.get("macs"))
            .cloned()
            .unwrap_or(json!({}));
        let digest = calculate_super_mac(seed, device_id, &macs_val)?;
        if let Some(prot) = root.as_object_mut().and_then(|o| o.get_mut("protection")).and_then(Value::as_object_mut) {
            prot.insert("super_mac".into(), json!(digest));
        }
    }
    Ok(())
}

fn merge_into_file(root: &mut Value, regs: &Map<String, Value>) -> Result<Map<String, Value>> {
    let ext = root
        .as_object_mut()
        .and_then(|o| o.entry("extensions").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|e| e.entry("settings").or_insert_with(|| json!({})).as_object_mut());
    let Some(ext) = ext else {
        return Err(Error::Corrupt("cannot merge into preferences file".into()));
    };
    for (id, entry) in regs {
        ext.insert(id.clone(), entry.clone());
    }
    Ok(ext.clone())
}

/// Merge extension registrations for Chrome-family targets.
///
/// Chrome 157 on Linux keeps `extensions.settings` and their MACs in plain
/// `Preferences` (verified live: a registration written only to
/// `Secure Preferences` is never read, while one in `Preferences` loads and
/// Chrome re-signs it). Registrations therefore go into `Preferences` with
/// freshly computed split MACs, and are mirrored into `Secure Preferences`
/// with MACs plus the super MAC for builds that read the protected store.
/// In `Preferences` the OSCrypt encrypted-hash anchors are dropped: that
/// copy is not the authoritative store on macOS and Linux Chrome re-signs
/// what it reads there. In `Secure Preferences`, when the caller passes
/// the target's macOS v11 lock (`anchor_lock`), each installed extension
/// also gets its `settings_encrypted_hash` anchor: on macOS Chrome does
/// NOT regenerate a missing anchor for a third-party entry, it strips
/// the entry and deletes its files at first startup (fix 3 round 2).
/// Without a lock (Linux, Windows, non-v11 macOS folders) no anchor is
/// written, exactly as before.
pub fn merge_registrations_secure(
    slot: &Path,
    browser: &str,
    regs: &Map<String, Value>,
    anchor_lock: Option<&Lock>,
) -> Result<usize> {
    if regs.is_empty() {
        return Ok(0);
    }
    let seed = seed_for_browser(browser);
    let device_id = chromium_device_id();

    let prefs_path = slot.join("Preferences");
    let mut prefs = read_json(&prefs_path)?;
    let settings = merge_into_file(&mut prefs, regs)?;
    macs_for_extensions(&mut prefs, &settings, seed, &device_id, false)?;
    if let Some(prot) = prefs
        .as_object_mut()
        .and_then(|o| o.get_mut("protection"))
        .and_then(Value::as_object_mut)
    {
        prot.remove("super_encrypted_hash");
        if let Some(ext) = prot
            .get_mut("macs")
            .and_then(|m| m.get_mut("extensions"))
            .and_then(Value::as_object_mut)
        {
            ext.remove("settings_encrypted_hash");
        }
    }
    write_json(&prefs_path, &prefs)?;

    let secure_path = slot.join("Secure Preferences");
    let mut secure = read_json(&secure_path)?;
    let secure_settings = merge_into_file(&mut secure, regs)?;
    macs_for_extensions(&mut secure, &secure_settings, seed, &device_id, true)?;
    if let Some(lock) = anchor_lock {
        stamp_settings_anchors(&mut secure, &secure_settings, regs, seed, lock)?;
    }
    write_json(&secure_path, &secure)?;
    Ok(regs.len())
}

/// Brave keeps registrations in plain `Preferences` only.
pub fn merge_registrations_brave(slot: &Path, regs: &Map<String, Value>) -> Result<usize> {
    if regs.is_empty() {
        return Ok(0);
    }
    let prefs_path = slot.join("Preferences");
    let mut prefs = read_json(&prefs_path)?;
    let settings = prefs
        .as_object_mut()
        .and_then(|o| o.entry("extensions").or_insert_with(|| json!({})).as_object_mut())
        .and_then(|e| e.entry("settings").or_insert_with(|| json!({})).as_object_mut());
    let Some(settings) = settings else {
        return Err(Error::Corrupt(format!("cannot merge into {}", prefs_path.display())));
    };
    let mut n = 0;
    for (id, entry) in regs {
        settings.insert(id.clone(), entry.clone());
        n += 1;
    }
    write_json(&prefs_path, &prefs)?;
    let secure = slot.join("Secure Preferences");
    if secure.is_file() {
        fs::remove_file(&secure).map_err(|e| io(e, "cannot remove", &secure))?;
    }
    Ok(n)
}

pub fn merge_registrations(
    slot: &Path,
    browser: &str,
    regs: &Map<String, Value>,
    anchor_lock: Option<&Lock>,
) -> Result<usize> {
    if uses_secure_extension_prefs(browser) {
        merge_registrations_secure(slot, browser, regs, anchor_lock)
    } else {
        merge_registrations_brave(slot, regs)
    }
}

