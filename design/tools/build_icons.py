#!/usr/bin/env python3
"""Pack our own icons (style/icons/*.svg, made by make_icons.py) plus two brand marks
(style/icons/brands/, Phosphor Icons 2.1.1, MIT, see brands/LICENSE.txt) into style/icons.js,
so screens can inline icons on file:// and in Tauri without fetch. Usage in HTML: <i data-icon="laptop"></i>"""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent / "style"
icons = {p.stem: p.read_text().strip() for p in sorted((root / "icons").glob("*.svg"))}
icons.update({p.stem: p.read_text().strip() for p in sorted((root / "icons" / "brands").glob("*.svg"))})
js = ("// Generated by tools/build_icons.py: Move It icons, plus brand marks from Phosphor Icons 2.1.1 (MIT).\n"
      "window.MOVEIT_ICONS = " + json.dumps(icons) + ";\n"
      "(function () {\n"
      "  function hydrate(root) {\n"
      "    (root || document).querySelectorAll('i[data-icon]').forEach(function (el) {\n"
      "      var svg = window.MOVEIT_ICONS[el.dataset.icon];\n"
      "      if (svg && !el.firstChild) { el.innerHTML = svg; el.classList.add('icon'); el.setAttribute('aria-hidden', 'true'); }\n"
      "    });\n"
      "  }\n"
      "  window.moveitIcons = hydrate;\n"
      "  if (document.readyState !== 'loading') hydrate(); else document.addEventListener('DOMContentLoaded', function () { hydrate(); });\n"
      "})();\n")
(root / "icons.js").write_text(js)
print(len(icons), "icons")
